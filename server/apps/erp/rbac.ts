/** Modules where create/edit of own document is allowed for employees even if not listed above. */
export function can(role: string, moduleId: string, action: ModuleAction): boolean {
  if (!ERP_ROLES.includes(role as ErpRole)) return false
  const perms = ROLE_PERMISSIONS[role as ErpRole][moduleId]
  if (!perms) return false
  return perms.includes(action)
}

/** Segregation of duties: finance users who create a journal cannot approve/post the same journal. */
export function sodAllowsPost(creator: string | null | undefined, actor: string, role: string): boolean {
  if (role === "sysadmin" || role === "auditor") return role !== "auditor"
  if (role === "finmgr") return !creator || creator !== actor
  if (role === "accountant") return false
  return can(role, "journals", "approve")
}
